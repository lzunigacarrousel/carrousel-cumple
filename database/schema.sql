CREATE TABLE IF NOT EXISTS schema_versions (version INT PRIMARY KEY, installed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cost_centers (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, source_park_id INT UNIQUE, code VARCHAR(50) NOT NULL UNIQUE,
 name VARCHAR(160) NOT NULL, park_name VARCHAR(160) NOT NULL, active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS roles (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL,
 permissions_json TEXT NOT NULL, is_system TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, source_user_id INT UNIQUE, name VARCHAR(140) NOT NULL,
 email VARCHAR(190) NULL UNIQUE, role_id INT UNSIGNED NOT NULL, center_id INT UNSIGNED NULL,
 active TINYINT NOT NULL DEFAULT 1, auth_version INT NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(role_id) REFERENCES roles(id), FOREIGN KEY(center_id) REFERENCES cost_centers(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS user_centers (
 user_id INT UNSIGNED NOT NULL, center_id INT UNSIGNED NOT NULL, PRIMARY KEY(user_id,center_id),
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(center_id) REFERENCES cost_centers(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS otp_codes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, challenge CHAR(48) NOT NULL UNIQUE, user_id INT UNSIGNED NOT NULL,
 code_hash VARCHAR(255) NOT NULL, session_hash CHAR(64) NOT NULL, attempts INT NOT NULL DEFAULT 0,
 expires_at DATETIME NOT NULL, consumed_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), INDEX(user_id,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS request_limits (
 limit_key CHAR(64) NOT NULL, bucket BIGINT NOT NULL, hits INT NOT NULL, PRIMARY KEY(limit_key,bucket)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS customers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, identity_key CHAR(64) NOT NULL UNIQUE,
 name VARCHAR(140) NOT NULL, day TINYINT UNSIGNED NOT NULL, month TINYINT UNSIGNED NOT NULL,
 email VARCHAR(190) NOT NULL, phone VARCHAR(30) NOT NULL, guardian VARCHAR(140) NOT NULL DEFAULT '', is_minor TINYINT NOT NULL DEFAULT 0,
 active TINYINT NOT NULL DEFAULT 1, terms_accepted_at DATETIME NOT NULL, terms_version VARCHAR(40) NOT NULL,
 marketing_opt_in TINYINT NOT NULL DEFAULT 0, registered_by INT UNSIGNED NOT NULL, center_id INT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL,
 FOREIGN KEY(registered_by) REFERENCES users(id), FOREIGN KEY(center_id) REFERENCES cost_centers(id), INDEX(month,day)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS registration_requests (
 user_id INT UNSIGNED NOT NULL, request_id VARCHAR(80) NOT NULL, payload_hash CHAR(64) NOT NULL,
 customer_id BIGINT UNSIGNED NOT NULL, PRIMARY KEY(user_id,request_id), FOREIGN KEY(customer_id) REFERENCES customers(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS campaigns (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(140) NOT NULL, benefit_type VARCHAR(20) NOT NULL,
 benefit_label VARCHAR(250) NOT NULL, quantity DECIMAL(12,2) NULL, terms TEXT NOT NULL,
 email_subject VARCHAR(180) NOT NULL, email_intro TEXT NOT NULL, start_date DATE NULL, end_date DATE NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'draft', version INT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS coupons (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, customer_id BIGINT UNSIGNED NOT NULL, campaign_id INT UNSIGNED NOT NULL,
 birthday_year SMALLINT NOT NULL, code VARCHAR(40) NOT NULL UNIQUE, token CHAR(64) NOT NULL UNIQUE,
 benefit_type VARCHAR(20) NOT NULL, benefit_label VARCHAR(250) NOT NULL, quantity DECIMAL(12,2) NULL,
 terms TEXT NOT NULL, email_subject VARCHAR(180) NOT NULL, email_intro TEXT NOT NULL,
 valid_from DATE NOT NULL, valid_until DATE NOT NULL, created_at DATETIME NOT NULL,
 redeemed_at DATETIME NULL, redeemed_by INT UNSIGNED NULL, redeemed_center_id INT UNSIGNED NULL,
 voided_at DATETIME NULL, voided_by INT UNSIGNED NULL, void_reason VARCHAR(500) NULL,
 UNIQUE(customer_id,campaign_id,birthday_year), FOREIGN KEY(customer_id) REFERENCES customers(id),
 FOREIGN KEY(campaign_id) REFERENCES campaigns(id), FOREIGN KEY(redeemed_by) REFERENCES users(id),
 FOREIGN KEY(redeemed_center_id) REFERENCES cost_centers(id), INDEX(valid_from,valid_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mail_queue (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, coupon_id BIGINT UNSIGNED NOT NULL UNIQUE, recipient VARCHAR(190) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending', attempts INT NOT NULL DEFAULT 0, next_attempt_at DATETIME NOT NULL,
 claimed_at DATETIME NULL, claim_token CHAR(48) NULL, last_error VARCHAR(500) NULL,
 message_id VARCHAR(180) NOT NULL UNIQUE, created_at DATETIME NOT NULL, sent_at DATETIME NULL,
 FOREIGN KEY(coupon_id) REFERENCES coupons(id), INDEX(status,next_attempt_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id INT UNSIGNED NULL,
 event VARCHAR(80) NOT NULL, entity VARCHAR(60) NOT NULL, entity_id VARCHAR(80) NULL, details TEXT NOT NULL,
 created_at DATETIME NOT NULL, INDEX(created_at), FOREIGN KEY(actor_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS runtime_state (state_key VARCHAR(80) PRIMARY KEY, state_value TEXT NOT NULL) ENGINE=InnoDB;
